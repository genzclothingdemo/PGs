"""Build db/seed.sql from the Gandhinagar CSVs (dedupe PGs, map homes). Run: python scripts/import_seed.py"""
import csv, re, os, json, hashlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'PG')
q = lambda v: 'null' if v in (None, '') else "'" + str(v).replace("'", "''") + "'"
num = lambda v: 'null' if v in (None, '') else str(v)

def digits(p): return re.sub(r'\D', '', p or '')[-10:]
def norm(n): return re.sub(r'[^a-z0-9]', '', (n or '').lower())

# ---- PGs ----
rows = list(csv.DictReader(open(os.path.join(D, 'Gandhinagar_PG_List.csv'), encoding='utf-8-sig')))
GENDER = {'boys': 'boys', 'girls': 'girls', 'both': 'both'}
seen, pgs = {}, []
for r in rows:
    key = (norm(r['Name']), digits(r['Phone']) or r['Lat'][:7] + r['Lng'][:7])
    if key in seen: continue
    seen[key] = 1
    if not r['Lat'] or not r['Lng']: continue
    pgs.append(r)

out = ['-- generated by scripts/import_seed.py (do not edit)', 'begin;']
for r in pgs:
    ref = 'pg-' + hashlib.md5((r['Name'] + r['Lat'] + r['Lng']).encode()).hexdigest()[:10]
    g = GENDER.get(r['Gender (Maps)'].lower(), 'not_stated')
    ph = digits(r['Phone'])
    out.append(
        "insert into properties (type,source,external_ref,name,gender,address,city_id,area_label,lat,lng,phone,category,hours,google_rating,google_reviews,status,verified,published_at) "
        f"select 'pg','imported',{q(ref)},{q(r['Name'])},'{g}',{q(r['Address'])},id,{q(r['Area'])},"
        f"{r['Lat']},{r['Lng']},{q(ph or None)},{q(r['Category'])},{q(r['Hours'])},"
        f"{num(r['Google rating'])},{num(r['Reviews'])},'published','unverified',now() from cities where slug='gandhinagar' on conflict do nothing;")

# ---- Rented homes ----
homes = list(csv.DictReader(open(os.path.join(D, 'Gandhinagar_Rental_Homes.csv'), encoding='utf-8-sig')))
nh = 0
for r in homes:
    rent = re.sub(r'\D', '', r['Monthly rent (INR)'] or '')
    if not rent: continue
    nh += 1
    ref = 'home-' + r['ID']
    bhk = re.search(r'([\d.]+)', r['BHK'] or '')
    sq = re.search(r'(\d+)', r['Area'] or '')
    name = f"{r['BHK']} {r['Type']} - {r['Society'] or r['Locality']}".strip()
    out.append(
        "with p as (insert into properties (type,source,external_ref,name,gender,address,city_id,area_label,category,description,listing_url,status,verified,published_at) "
        f"select 'home','imported',{q(ref)},{q(name)},'not_stated',{q(r['Locality'])},id,{q(r['Locality'])},{q(r['Type'])},{q(r['Notes'])},{q(r['Listing URL'])},'published','unverified',now() "
        "from cities where slug='gandhinagar' on conflict do nothing returning id) "
        f"insert into units (property_id,label,bhk,area_sqft,furnishing,rent) select id,{q(r['BHK'])},{num(bhk.group(1) if bhk else None)},{num(sq.group(1) if sq else None)},null,{rent} from p;")
out.append('commit;')
open(os.path.join(ROOT, 'db', 'seed.sql'), 'w', encoding='utf-8').write('\n'.join(out))
print(f'raw PG rows {len(rows)} -> unique with coordinates {len(pgs)}; homes {nh}')
from collections import Counter
print(Counter(GENDER.get(r['Gender (Maps)'].lower(), 'not_stated') for r in pgs))
